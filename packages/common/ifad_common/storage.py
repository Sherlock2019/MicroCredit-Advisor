"""Object storage for uploaded documents: a local filesystem adapter (Docker volume) and an Azure Blob adapter.

Keys are generated by the platform (tenant/domain/scope/uuid-filename), never taken from the client.
"""
from __future__ import annotations

import hashlib
import re
from functools import lru_cache
from pathlib import Path
from typing import Protocol

from ifad_common.config import get_settings

_SAFE_NAME = re.compile(r"[^A-Za-z0-9._-]+")


def safe_filename(name: str) -> str:
    cleaned = _SAFE_NAME.sub("_", Path(name or "upload").name).strip("._") or "upload"
    return cleaned[:120]


class ObjectStorage(Protocol):
    backend: str

    def put(self, key: str, data: bytes, content_type: str) -> str: ...
    def get(self, key: str) -> bytes: ...
    def health(self) -> tuple[bool, str]: ...


class LocalObjectStorage:
    backend = "local"

    def __init__(self, root: str):
        self.root = Path(root).resolve()

    def _path(self, key: str) -> Path:
        path = (self.root / key).resolve()
        if not path.is_relative_to(self.root):
            raise ValueError("storage key escapes the storage root")
        return path

    def put(self, key: str, data: bytes, content_type: str) -> str:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        return f"local://{key}"

    def get(self, key: str) -> bytes:
        return self._path(key).read_bytes()

    def health(self) -> tuple[bool, str]:
        try:
            self.root.mkdir(parents=True, exist_ok=True)
            probe = self.root / ".health"
            probe.write_text("ok")
            return True, "local object store writable"
        except OSError as exc:
            return False, type(exc).__name__


class AzureBlobStorage:
    """Uses the workload identity (DefaultAzureCredential); no account keys. Requires the `azure` extra.

    Not exercised by the local test suite (no Azure account in Phases 1-4).
    """

    backend = "azure_blob"

    def __init__(self, account_url: str, container: str):
        from azure.identity import DefaultAzureCredential
        from azure.storage.blob import BlobServiceClient

        self.client = BlobServiceClient(account_url, credential=DefaultAzureCredential()).get_container_client(container)

    def put(self, key: str, data: bytes, content_type: str) -> str:
        from azure.storage.blob import ContentSettings

        self.client.upload_blob(key, data, overwrite=False, content_settings=ContentSettings(content_type=content_type))
        return f"azblob://{self.client.container_name}/{key}"

    def get(self, key: str) -> bytes:
        return self.client.download_blob(key).readall()

    def health(self) -> tuple[bool, str]:
        try:
            self.client.get_container_properties()
            return True, "blob container reachable"
        except Exception as exc:  # noqa: BLE001
            return False, type(exc).__name__


@lru_cache
def get_storage() -> ObjectStorage:
    settings = get_settings()
    if settings.storage_backend == "azure_blob":
        return AzureBlobStorage(settings.azure_storage_account_url, settings.azure_storage_container)
    return LocalObjectStorage(settings.storage_local_root)


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()
